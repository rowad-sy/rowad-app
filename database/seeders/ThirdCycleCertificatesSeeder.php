    private function ensureSigner(?string $name, string $role, string $prefix, int &$seq): ?int
    {
        if ($name === null || trim($name) === '') {
            return null;
        }
        $name = trim($name);

        $existing = CertificateSigner::where('name_ar', $name)->where('role', $role)->first();
        if ($existing) {
            return $existing->id;
        }

        $seq++;
        return CertificateSigner::create([
            'code' => $prefix . '-' . str_pad((string) $seq, 3, '0', STR_PAD_LEFT),
            'name_ar' => $name,
            'role' => $role,
        ])->id;
    }

    /*
     * يبني خريطة الأكواد التي سيستخدمها السينر بنفس ترتيب التكرار في run():
     * student_code => "الاسم الكامل".
     */
    private function intendedStudents(): array
    {
        $map = [];
        $codeNum = self::START_CODE;
        foreach (self::CENTERS as $data) {
            foreach ($data['rows'] as $row) {
                $code = 'STU-' . str_pad((string) $codeNum, 5, '0', STR_PAD_LEFT);
                $codeNum++;
                $map[$code] = preg_replace('/\s+/u', ' ', trim($row[0]));
            }
        }
        return $map;
    }

    /*
     * حارس أمان: يفحص تعارض الأكواد قبل أي كتابة.
     * - كود محجوز لطالب آخر باسم مختلف → تصادم (يوقف السينر حتى لا يدهس بيانات قائمة).
     * - كود لطالب محذوف soft-deleted بنفس الاسم → سنُعيده ثم نُحدّثه (مقبول).
     * يُرجع مصفوفة رسائل التصادم (فارغة = آمن).
     */
    private function detectConflicts(array $intended): array
    {
        $conflicts = [];
        $existing = Student::withTrashed()
            ->whereIn('student_code', array_keys($intended))
            ->get()
            ->keyBy('student_code');

        foreach ($intended as $code => $fullName) {
            $student = $existing->get($code);
            if (!$student) {
                continue; // الكود حر
            }
            if (preg_replace('/\s+/u', ' ', trim($student->first_name_ar . ' ' . $student->last_name_ar)) !== $fullName) {
                $conflicts[] = $code . ' محجوز مسبقاً لـ"' . $student->first_name_ar . ' ' . $student->last_name_ar
                    . '" لكنه في هذا الملف "«' . $fullName . '»"';
            }
        }
        return $conflicts;
    }

